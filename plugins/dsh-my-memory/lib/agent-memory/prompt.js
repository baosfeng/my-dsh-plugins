/**
 * dsh-my-memory — agent 记忆的系统提示词说明段（issue #502）。
 *
 * **正文零常驻，目录常驻**（issue #502 后续）：
 *  - 说明段恒等（规则 + 用法），不含任何记忆正文；
 *  - **目录段动态**：一行一条列出 agent 自己写过的条目（catalog.ts 生成），
 *    解决「不读不知道有什么、读了才知道」的死结——按需读取把「想起来去
 *    list」压在模型自觉上，靠不住；Claude Code 的解法也是索引常驻。
 *  - 正文仍只在 agent_memory_read 时才进上下文，不命中一分不花。
 *
 * 写入原则硬编码在这里、不进记忆文件：agent 可以写记忆内容，但改不了
 * 规则本身——这是「写入之后禁止修改」的正确落法。
 */
/** 系统提示词段的顺序（记忆正文段 -95、全局提示词 -85，本段紧随其后）。 */
const AGENT_MEMORY_SECTION_ORDER = -80;
/** 固定说明正文（不含任何记忆内容）。 */
export const AGENT_MEMORY_SECTION_TEXT = `## 跨会话记忆

你有一份自己的跨会话记忆，用来记住下次会话还用得上的信息与用户偏好。它独立于全局记忆与项目记忆，由你自己维护。

**位置**：\`~/.dsh/agent-memory/\`（只能通过本节的工具访问，不要用 bash 或 read 直接翻）。

**目录在下面**：「我的记忆目录」一节一行一条列出了你写过的全部条目（含它属于哪个文件）。正文不在上下文里——判断哪条相关，再用 \`agent_memory_read\` 读它所在的文件。行尾的「…」只是这条摘要太长被截短，不是目录不全；只有出现「另有 N 条未展开」才说明目录被截断，那时用 \`agent_memory_list\` 看全量。

**默认写项目层**：先问「换个项目还成立吗」。
- 不成立 → \`projects/current/…\`：含仓库名、路径、脚本、命令、端口、IP、版本号，或某个项目的 UI 裁决与部署方式。
- 成立，且**对别的项目也有帮助** → \`user.md\` / \`feedback.md\`。
- 拿不准就写项目层——写错项目的代价，远小于污染全局。

**进全局要过两问**（任一为否就写项目层）：
1. 这是不是一种**通用能力**：换任何一个仓库，这句话仍然指导你做事？（方法、流程、工具偏好、交付格式、文档风格、环境约定、通用安全纪律）
2. 它对**其他项目**有没有帮助：别的项目的人看了能不能直接用上？（具体部署地址、某个页面怎么排版、某个仓库的发布流程都不算）
含项目专属标识（仓库名 / 绝对路径 / \`scripts/…\` / IP / 端口）的条目写全局会被工具直接拒绝。

**怎么用**：
- 目录里看到相关的，再 read 正文；不要凭印象猜目录内容。
- \`agent_memory_write\` 整份覆盖；先 read 再写，已有同主题就合并或替换。

**什么时候写**：
- 用户明确说「记住」「以后都…」「不要再…」；
- 用户纠正了你的做法（记下被纠正的与正确做法）；
- 你发现了一条下次会话还用得上、且从代码/仓库/git 历史推不出来的信息。

**写入原则（不可违反）**：
1. 一句话。一条一件事。不解释、不铺垫、不写「注意」「请务必」。
2. 只写通用的——跨会话、跨任务仍成立的才写。这次任务的细节不写。
3. 不写能推导的——架构、文件路径、依赖关系、debug 过程都不写（项目层的具体命令 / 路径正是它的价值，不受本条限制）。
4. 决策类必须带理由（选 X 因为 Y），否则未来会重复讨论；理由只写用户给出的，不自行补因果。
5. 先读再写。已有同主题就按下面「遇到矛盾时」的判据合并或替换，绝不新增重复条目。
6. **不要写日期**。系统会自动记录时间，写了就是浪费上下文。
7. 已经有的不写：全局记忆 / 项目记忆 / 全局提示词里的，以及仓库里的（AGENTS.md、README、CI 配置）——后者你自己读得到。比已有约束更具体的可以写（「一律中文」强于「默认中文」）。
8. 敏感信息零容忍：密钥、token、密码、个人隐私永不写。
9. **宁缺毋滥。空文件是合法的，写满不是目标。**
10. 发现新旧矛盾：按下面一节处理，绝不留两条并存。

**遇到矛盾时**：
- 先分清真假：不同场景、不同对象的偏好不是矛盾，用限定语写清（「前端用 pnpm，后端用 npm」）——能共存就别删。
- 真矛盾（同一对象、同一维度、互斥取值）：写新的、删旧的；演进有解释价值时写成「（原 X，现 Y）」一句，不留两条并存。
- 写不进去（已满）时先整理：合并近义条目、删被取代的、精简措辞，再写。

**尺寸与确认**：单文件上限 60 条 / 4 KB，超了会整体拒绝写入（原文件不动），按上一节先整理再写。写入成功只回一个 \`ok\`，想确认内容就再 read 一次。

**文件分工**：
- \`user.md\` —— 跨项目通用的用户偏好与能力（只收过了上面两问的内容）。
- \`feedback.md\` —— 用户纠正过你的做法 + 正确做法。同一件事只写一处：「我原来做错了」→ feedback.md；「用户要求的习惯」→ user.md。
- \`projects/current/decisions.md\` —— 当前项目的决策 + 为什么。
- \`projects/current/pitfalls.md\` —— 当前项目踩过的坑 + 怎么绕；用户在本项目纠正过你的做法也记这里。
- 写的时候一律用 \`projects/current/…\`（系统解析成真实项目，别自己拼 id）；\`list\` / \`read\` 返回的 \`projects/<id>/…\` 是同一个文件，照用即可。
- \`MEMORY.md\` —— 可选索引：一行一个文件 + 什么时候该读它。`;
/** 目录段（动态：一行一条；空库时给一句「还没有记忆」）。 */
function catalogBlock(rows) {
    if (rows.trim() === '') {
        return '## 我的记忆目录\n\n（还没有记忆——这是正常状态。只有遇到下次会话仍有用、且代码里推不出来的信息时才写。）';
    }
    return '## 我的记忆目录\n\n一行一条，前缀是它所在的文件。正文不在上面，读命中的那一份即可。\n\n' + rows;
}
/** 构造系统提示词 section（说明恒等 + 目录动态）。 */
export function createAgentMemorySection(catalog) {
    return {
        name: 'dsh-my-memory:agent-memory',
        order: AGENT_MEMORY_SECTION_ORDER,
        text: () => AGENT_MEMORY_SECTION_TEXT + '\n\n' + catalogBlock(catalog.text()),
    };
}
